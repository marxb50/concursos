/* Áudio real e controles: executar sobre o servidor local da pasta dist. */
async page => {
  const context=await page.context().browser().newContext({viewport:{width:1366,height:900},reducedMotion:'reduce'});
  const probe=await context.newPage(),errors=[],passed=[];
  probe.setDefaultTimeout(15000);
  probe.setDefaultNavigationTimeout(20000);
  const check=(ok,message)=>{if(!ok)throw new Error(message);};let stage='início';
  probe.on('pageerror',e=>errors.push(e.message));
  await probe.addInitScript(()=>{const OriginalAudio=window.Audio;window.Audio=function(...args){const a=new OriginalAudio(...args);window.__professorAudio=a;return a;};});
  const visit=async hash=>{await probe.goto('http://127.0.0.1:8765/'+hash);await probe.locator('main').waitFor();};
  try{
    await visit('#historia/sql');
    check(await probe.evaluate(()=>window.__professorAudio.paused&&!window.__professorAudio.src),'Sem reprodução automática');
    await probe.locator('#listen').click();
    stage='reprodução inicial';
    await probe.waitForFunction(()=>window.__professorAudio.currentTime>0.1&&!window.__professorAudio.paused);
    check((await probe.locator('#professor-voice').innerText()).includes('Thalita Neural'),'Voz identificada');
    check(await probe.evaluate(()=>window.__professorAudio.duration>10),'MP3 real decodificado');
    await probe.locator('#professor-minimize').click();
    check(!(await probe.locator('#professor-body').isVisible())&&!await probe.evaluate(()=>window.__professorAudio.paused),'Recolher libera a figura e mantém o áudio');
    await probe.locator('#professor-minimize').click();
    await probe.locator('#professor-play').click();
    check(await probe.evaluate(()=>window.__professorAudio.paused),'Pausa real');
    await probe.locator('#professor-play').click();
    stage='retomada';
    await probe.waitForFunction(()=>!window.__professorAudio.paused);
    await probe.locator('#professor-speed').selectOption('1.15');
    check(await probe.evaluate(()=>window.__professorAudio.playbackRate)===1.15,'Velocidade aplicada');
    await probe.locator('#professor-repeat').click();
    stage='repetição';
    await probe.waitForFunction(()=>window.__professorAudio.currentTime<2&&!window.__professorAudio.paused);
    passed.push('Áudio Thalita real, pausa, retomada, velocidade e repetição');
    await probe.locator('#professor-part-select').selectOption('4');
    stage='seek para pergunta';
    await probe.waitForFunction(()=>window.__professorAudio.currentTime>30&&!window.__professorAudio.paused);
    await probe.evaluate(()=>{const l=ProfessorCore.scene('sql',0),clip=PROFESSOR_AUDIO.tracks[ProfessorCore.fingerprint(l)].segments[4];window.__professorAudio.currentTime=clip.end-.005;});
    stage='pausa antes da resposta';
    await probe.waitForFunction(()=>window.__professorAudio.paused);
    check(await probe.locator('#professor-part-select').inputValue()==='4','Pausa antes da resposta');
    check(await probe.locator('#professor-next').innerText()==='Conferir →','Conferência voluntária');
    await probe.locator('#professor-next').click();
    check(await probe.locator('#professor-part-select').inputValue()==='5','Conferir revela resposta');
    await probe.locator('#professor-review').click();
    check(await probe.evaluate(()=>JSON.parse(localStorage.getItem('memoria-viva-revisoes-v1')).some(x=>x.id==='sql')),'Guardar assunto');
    await probe.locator('#professor-close').click();
    check(await probe.evaluate(()=>window.__professorAudio.paused),'Fechar interrompe áudio');
    check(await probe.locator('#listen').evaluate(el=>el===document.activeElement),'Foco volta ao botão');
    await probe.locator('#enlarge').click();
    await probe.locator('#art-dialog [data-professor]').click();
    check(!(await probe.locator('#art-dialog').isVisible())&&await probe.locator('#professor-panel').isVisible(),'Professor na ilustração ampliada');
    await probe.locator('#professor-close').click();
    check(await probe.locator('#enlarge').evaluate(el=>el===document.activeElement),'Retorno da ilustração ampliada');
    passed.push('Recuperação ativa, revisão e foco acessível');
    for(const hash of ['#concursos','#concurso/natal-suporte-2023','#materia/cgu-dev-2026/persistencia','#mapa/mat_equacoes','#infograficos/planilhas-mapa','#revisao','#estrategia','#fontes']){
      await visit(hash);
      const bar=probe.locator('.view:not([hidden]) > .professor-page-bar [data-professor]');
      check(await bar.count()===1,'Professor em '+hash);
      await bar.click();
      check(await probe.locator('#professor-text').isVisible(),'Roteiro em '+hash);
      await probe.locator('#professor-close').click();
    }
    passed.push('Professor em todas as nove telas');
    await visit('#infograficos/planilhas-mapa');
    check(await probe.locator('.inf-group>.professor-button').count()===await probe.locator('.inf-group').count(),'Cada bloco tem professora');
    await probe.locator('.mini-lab>.professor-button').click();
    check((await probe.locator('#professor-title').innerText()).includes('Fórmulas'),'Laboratório tem explicação própria');
    await probe.locator('#professor-close').click();
    await probe.locator('.inf-group>.professor-button').nth(1).click();
    check((await probe.locator('#professor-part-title').innerText()).startsWith('Bloco 2'),'Professor abre bloco selecionado');
    await probe.locator('#professor-close').click();
    await probe.locator('.view:not([hidden]) > .professor-page-bar [data-professor]').click();
    await probe.getByRole('link',{name:'Concursos',exact:true}).click();
    await probe.locator('#view-concursos').waitFor({state:'visible'});
    check(!(await probe.locator('#professor-panel').isVisible()),'Troca de tela fecha professora');
    check(await probe.evaluate(()=>window.__professorAudio.paused),'Troca de tela interrompe áudio');
    passed.push('Mapas, blocos, laboratório e troca segura de contexto');
    await probe.setViewportSize({width:390,height:844});
    await visit('#historia/sql');await probe.locator('#listen').click();
    check(await probe.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Sem transbordamento no celular');
    check(await probe.locator('#professor-close').isVisible()&&await probe.locator('#professor-play').isVisible(),'Controles visíveis no celular');
    await probe.screenshot({path:'output/playwright/professora-mobile.png'});
    await probe.emulateMedia({media:'print'});await probe.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
    check(!(await probe.locator('#professor-panel').isVisible()),'Painel fora da impressão');
    check(await probe.evaluate(()=>window.__professorAudio.paused),'Impressão pausa voz');
    await probe.evaluate(()=>window.dispatchEvent(new Event('afterprint')));await probe.emulateMedia({media:'screen'});
    passed.push('Celular e impressão');
    check(errors.length===0,errors.join('; '));
    return {passed,errors};
  }catch(error){throw new Error(stage+': '+error.message+' '+JSON.stringify(await probe.evaluate(()=>({status:document.querySelector('#professor-status')?.textContent,part:document.querySelector('#professor-part-select')?.value,audio:window.__professorAudio?{time:window.__professorAudio.currentTime,paused:window.__professorAudio.paused,ready:window.__professorAudio.readyState,error:window.__professorAudio.error?.message}:null}))));}finally{await context.close();}
}
